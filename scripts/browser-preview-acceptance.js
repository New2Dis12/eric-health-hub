// Run once in the signed-in browser Console on the isolated PR #6 Preview.
// Uses synthetic training records only. Never paste cookies, tokens or secrets.
(async () => {
  const checks = [];
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  assert(location.origin === 'https://eric-health-hub-git-feature-stunna-sprint-1-stunna4.vercel.app', 'Wrong origin: use the PR #6 Preview');
  const key = () => crypto.randomUUID();
  const command = fields => ({ idempotencyKey: key(), reason: 'Synthetic Sprint 1 acceptance', ...fields });
  const request = async (method, body, expected = 200, headers = {}) => {
    const response = await fetch('/api/training', { method, cache: 'no-store', credentials: 'same-origin', headers: { ...(body ? { 'Content-Type': 'application/json' } : {}), ...headers }, ...(body ? { body: JSON.stringify(body) } : {}) });
    assert(response.status === expected, `${body?.operation || method}: expected ${expected}, received ${response.status}`);
    assert(response.headers.get('content-type')?.includes('application/json'), 'Expected application JSON');
    assert(response.headers.get('cache-control')?.includes('no-store'), 'Missing no-store response');
    return response.json();
  };
  const post = (body, expected = 200) => request('POST', body, expected);
  const initial = await request('GET');
  assert(['blocks', 'plans', 'sessions', 'measurements'].every(k => initial[k]?.length === 0), 'Database is not empty; stop rather than rerunning');
  checks.push('authenticated read');
  const block = await post(command({ operation: 'create_block', block: { title: 'SYNTHETIC Sprint 1 acceptance', goal: 'Persistence test only', startsOn: '2026-01-01', endsOn: '2026-01-31', source: 'manual' } }));
  const plan = await post(command({ operation: 'create_planned_session', plan: { blockId: block.blockId, scheduledAt: '2026-01-02T12:00:00Z', timeZone: 'UTC', kind: 'run', purpose: 'SYNTHETIC test only', source: 'manual' } }));
  const measurement = { kind: 'weight', value: 100, unit: 'kg', measuredAt: '2026-01-02T12:00:00Z', timeZone: 'UTC' };
  const session = { plannedSessionId: plan.plannedSessionId, expectedRevision: 0, startedAt: '2026-01-02T12:00:00Z', completedAt: null, status: 'in_progress', notes: 'SYNTHETIC test only', rpe: 5 };
  const write = command({ operation: 'record_observation', measurement, session });
  const saved = await post(write);
  sessionStorage.setItem('stunna-sprint1-acceptance', JSON.stringify({ blockId: block.blockId, plan, saved, write }));
  let history = await request('GET');
  assert(history.sessions.length === 1 && history.measurements.length === 1, 'Atomic save/read count mismatch');
  assert(history.sessions[0].id === saved.actualSessionId && history.measurements[0].id === saved.measurementId && history.measurements[0].value === 100 && history.measurements[0].unit === 'kg', 'Saved records do not match');
  checks.push('atomic session + measurement write/read');
  const replay = await post(write);
  assert(['actualSessionId', 'measurementId', 'sessionRevision'].every(k => replay[k] === saved[k]), 'Retry changed result');
  checks.push('idempotent retry');
  await post({ ...write, measurement: { ...measurement, value: 101 } }, 409);
  await post(command({ operation: 'record_observation', session }), 409);
  checks.push('idempotency and stale revision conflicts');
  await post(command({ operation: 'record_observation', measurement, session: { ...session, plannedSessionId: key() } }), 404);
  history = await request('GET');
  assert(history.sessions.length === 1 && history.measurements.length === 1, 'Failed transaction left records behind');
  checks.push('atomic rollback');
  await post(command({ operation: 'record_observation', measurement: { ...measurement, unit: 'cm' } }), 400);
  checks.push('invalid unit rejection');
  const completed = { ...session, expectedRevision: 1, status: 'completed', completedAt: '2026-01-02T13:00:00Z' };
  const completion = command({ operation: 'record_observation', session: completed });
  const concurrent = await Promise.all([post(completion), post(completion)]);
  assert(concurrent.every(r => r.actualSessionId === saved.actualSessionId && r.sessionRevision === 2), 'Concurrent completion duplicated or changed revision');
  checks.push('concurrent idempotent completion');
  const correction = await post(command({ operation: 'record_observation', session: { ...completed, expectedRevision: 2, notes: 'SYNTHETIC audited correction' } }));
  assert(correction.sessionRevision === 3, 'Correction revision mismatch');
  await post(command({ operation: 'record_observation', session: { ...session, expectedRevision: 3 } }), 409);
  checks.push('revision correction and finalized-session protection');
  await request('GET', null, 401, { Authorization: 'Bearer invalid-synthetic-token' });
  await request('POST', command({ operation: 'record_observation', measurement }), 401, { Authorization: 'Bearer invalid-synthetic-token' });
  checks.push('invalid bearer cannot fall back to browser session');
  history = await request('GET');
  assert(history.blocks.length === 1 && history.plans.length === 1 && history.sessions.length === 1 && history.measurements.length === 1, 'Final counts differ');
  assert(history.sessions[0].revision === 3 && history.sessions[0].status === 'completed' && history.sessions[0].notes === 'SYNTHETIC audited correction', 'Final session mismatch');
  console.log(JSON.stringify({ result: 'PASS', checks, counts: { blocks: 1, plans: 1, sessions: 1, measurements: 1 }, finalRevision: 3 }));
})().catch(error => console.error(JSON.stringify({ result: 'FAIL', message: error.message, action: 'Stop and report; do not rerun' })));
